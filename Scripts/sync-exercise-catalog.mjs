import { readFileSync, writeFileSync } from "node:fs";

// A classic script also works when the Windows preview is opened via file://.
const source = new URL("../BodyNoteCore/Sources/BodyNoteCore/Resources/exercise-catalog.json", import.meta.url);
const target = new URL("../Preview/exercise-catalog-data.js", import.meta.url);
const json = readFileSync(source, "utf8").trim().replace(/\r\n/g, "\n");
JSON.parse(json);
const output = "// Generated by Scripts/sync-exercise-catalog.mjs\nconst exerciseCatalog = " + json + ";\n";
if (process.argv.includes("--check")) {
  if (readFileSync(target, "utf8").replace(/\r\n/g, "\n") !== output) {
    throw Error("Refresh the offline catalog with node Scripts/sync-exercise-catalog.mjs");
  }
} else {
  writeFileSync(target, output);
}
